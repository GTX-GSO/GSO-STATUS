# Regenerates simulator/provider_icons.h: 20x20 ARGB8888 marks for the VIBE provider labels.
# Sources are the logos shipped inside the locally installed Codex (OpenAI mark, white) and Claude desktop
# apps; the generated header is the only thing the simulator and firmware compile.
param(
    [string]$CodexPackage = (Get-ChildItem 'C:\Program Files\WindowsApps' -Directory -Filter 'OpenAI.Codex_*' | Sort-Object Name | Select-Object -Last 1 -ExpandProperty FullName),
    [string]$ClaudePackage = (Get-ChildItem 'C:\Program Files\WindowsApps' -Directory -Filter 'Claude_*' | Sort-Object Name | Select-Object -Last 1 -ExpandProperty FullName),
    [int]$Size = 20
)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root = Split-Path $PSScriptRoot
$target = Join-Path $root 'simulator/provider_icons.h'

# Alpha mask (0..1) of a source image after an optional per-pixel rule, cropped to its visible bounds and resampled.
function Get-Mask([string]$path, [scriptblock]$rule, [int]$size, [double]$margin) {
    $img = [System.Drawing.Bitmap]::FromFile($path)
    try {
        $w = $img.Width; $h = $img.Height
        $alpha = New-Object 'double[]' ($w * $h)
        $minX = $w; $minY = $h; $maxX = -1; $maxY = -1
        for ($y = 0; $y -lt $h; $y++) {
            for ($x = 0; $x -lt $w; $x++) {
                $p = $img.GetPixel($x, $y)
                $a = & $rule $p
                $alpha[$y * $w + $x] = $a
                if ($a -gt 0.3) { if ($x -lt $minX) { $minX = $x }; if ($x -gt $maxX) { $maxX = $x }; if ($y -lt $minY) { $minY = $y }; if ($y -gt $maxY) { $maxY = $y } }
            }
        }
    } finally { $img.Dispose() }
    $side = [Math]::Max($maxX - $minX + 1, $maxY - $minY + 1) * (1 + $margin)
    $cx = ($minX + $maxX + 1) / 2.0; $cy = ($minY + $maxY + 1) / 2.0
    $left = $cx - $side / 2; $top = $cy - $side / 2; $cell = $side / $size
    $out = New-Object 'double[]' ($size * $size)
    for ($ty = 0; $ty -lt $size; $ty++) {
        for ($tx = 0; $tx -lt $size; $tx++) {
            $x0 = $left + $tx * $cell; $y0 = $top + $ty * $cell; $sum = 0.0; $area = 0.0
            for ($sy = [Math]::Floor($y0); $sy -lt [Math]::Ceiling($y0 + $cell); $sy++) {
                for ($sx = [Math]::Floor($x0); $sx -lt [Math]::Ceiling($x0 + $cell); $sx++) {
                    $wx = [Math]::Min($sx + 1, $x0 + $cell) - [Math]::Max($sx, $x0); $wy = [Math]::Min($sy + 1, $y0 + $cell) - [Math]::Max($sy, $y0)
                    $weight = $wx * $wy; $area += $weight
                    if ($sx -ge 0 -and $sx -lt $w -and $sy -ge 0 -and $sy -lt $h) { $sum += $alpha[$sy * $w + $sx] * $weight }
                }
            }
            $out[$ty * $size + $tx] = if ($area -gt 0) { $sum / $area } else { 0 }
        }
    }
    return ,$out
}

function Format-Array([string]$name, [double[]]$mask, [int]$r, [int]$g, [int]$b, [int]$size) {
    $rows = for ($y = 0; $y -lt $size; $y++) {
        $cells = for ($x = 0; $x -lt $size; $x++) { '0x{0:X2},0x{1:X2},0x{2:X2},0x{3:X2}' -f $b, $g, $r, ([int][Math]::Round([Math]::Min(1.0, $mask[$y * $size + $x]) * 255)) }
        ' ' + ($cells -join ',') + ','
    }
    "static const uint8_t $name[GSO_PROVIDER_ICON_SIZE*GSO_PROVIDER_ICON_SIZE*4]={`n" + ($rows -join "`n") + "`n};"
}

# OpenAI mark: the app ships it as a white glyph on transparency, so its alpha channel is the shape.
$codexSource = Join-Path $CodexPackage 'assets/Square44x44Logo.targetsize-256_altform-unplated.png'
$codex = Get-Mask $codexSource { param($p) $p.A / 255.0 } $Size 0.0
# Claude: the app icon is a cream burst on an orange tile; keep the burst (bright pixels) and paint it brand orange.
$claudeSource = Join-Path $ClaudePackage 'assets/Square44x44Logo.targetsize-256.png'
$claude = Get-Mask $claudeSource { param($p) $v = ($p.G - 130) / 105.0; [Math]::Max(0.0, [Math]::Min(1.0, $v)) * ($p.A / 255.0) } $Size 0.04

$header = @"
/* Generated by scripts/generate-provider-icons.ps1 - do not edit by hand.
   20x20 ARGB8888 (straight alpha, B,G,R,A byte order) marks taken from the locally installed Codex and Claude
   desktop apps: OpenAI mark in white, Claude burst in Claude orange. */
#pragma once
#include <stdint.h>
#define GSO_PROVIDER_ICON_SIZE $Size
$(Format-Array 'gso_codex_icon_pixels' $codex 255 255 255 $Size)
$(Format-Array 'gso_claude_icon_pixels' $claude 0xD9 0x77 0x57 $Size)
"@
[IO.File]::WriteAllText($target, $header, (New-Object System.Text.UTF8Encoding($false)))
Write-Output "Wrote $target"
