"""Regenerates simulator/car_image.h: the exterior picture shown on the CAR card (and its detail page).

The source is assets/leapmotor-car-c11.png, a transparent cut-out of the coloured C11 supplied by the user (soft translucent ground shadow included).
The result is straight-alpha ARGB8888 (one 0xAARRGGBB word per pixel, i.e. B,G,R,A bytes in memory on the little-endian
ESP32-P4 and the Windows simulator), resampled on premultiplied colour so the edge does not pick up a dark fringe.
Run with Pillow: python scripts/generate-car-image.py [width]
"""
import pathlib
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "leapmotor-car-c11.png"
TARGET = ROOT / "simulator" / "car_image.h"


def clean_alpha(image: Image.Image) -> Image.Image:
    """The supplied cut-out is already clean; the lossy source only leaves the body at alpha 253-254, so snap that to opaque."""
    result = image.copy()
    result.putalpha(image.getchannel("A").point(lambda a: 255 if a >= 245 else a))
    return result


def main() -> int:
    width = int(sys.argv[1]) if len(sys.argv) > 1 else 280
    image = clean_alpha(Image.open(SOURCE).convert("RGBA"))
    box = image.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox()
    if box is None:
        print("FAIL: the source picture is fully transparent")
        return 1
    image = image.crop(box)
    height = round(image.height * width / image.width)
    premultiplied = image.copy()
    pixels = premultiplied.load()
    for y in range(premultiplied.height):
        for x in range(premultiplied.width):
            r, g, b, a = pixels[x, y]
            pixels[x, y] = (r * a // 255, g * a // 255, b * a // 255, a)
    small = premultiplied.resize((width, height), Image.LANCZOS)
    out = []
    raw = small.tobytes()
    for r, g, b, a in zip(raw[0::4], raw[1::4], raw[2::4], raw[3::4]):
        if a:
            r, g, b = (min(255, c * 255 // a) for c in (r, g, b))
        else:
            r = g = b = 0
        out.append(f"0x{a:02X}{r:02X}{g:02X}{b:02X}")
    lines = [", ".join(out[i:i + 12]) for i in range(0, len(out), 12)]
    TARGET.write_text(
        "/* Generated by scripts/generate-car-image.py - do not edit by hand.\n"
        "   Exterior picture of the Leapmotor C11 (assets/leapmotor-car-c11.png), straight-alpha ARGB8888,\n"
        "   one 0xAARRGGBB word per pixel (B,G,R,A byte order on little-endian targets). */\n"
        "#pragma once\n#include <stdint.h>\n"
        f"#define GSO_CAR_IMAGE_W {width}\n#define GSO_CAR_IMAGE_H {height}\n"
        "static const uint32_t gso_car_image_pixels[GSO_CAR_IMAGE_W*GSO_CAR_IMAGE_H]={\n "
        + ",\n ".join(lines) + "\n};\n",
        encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}: {width}x{height}, {TARGET.stat().st_size} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
